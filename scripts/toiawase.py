"""市町への問い合わせの一覧を、データから作る。

「確認できず」と未着手のマスを市町ごとに拾い、聞くことを並べる。
使い方: python scripts/toiawase.py   (docs/問い合わせ.md を書き換える)
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from futoko_lod import schema  # noqa: E402

KINDS = ["fs-hojo", "shien-center", "online", "shusseki"]  # 学びの多様化学校は国の一覧で確かめるので聞かない

QUESTION = {
    "fs-hojo": "フリースクール等を利用する児童生徒の保護者に、利用料を補助する制度はありますか。ある場合は、制度名と、案内のページまたは要綱の場所を教えてください。",
    "shien-center": "教育支援センター(適応指導教室)にあたる、学校の外で通える教室はありますか。ある場合は、名前と、案内のページを教えてください。",
    "online": "市(町)が行う、不登校の児童生徒向けのオンラインの学習支援や居場所はありますか(県の事業を除きます)。",
    "shusseki": "フリースクール等の民間施設での活動を出席扱いにする際の、市(町)としての要綱やガイドラインはありますか。公表されていますか。また、出席扱いにしている施設の一覧を公表されていますか。",
}

# 種類の境目など、「あり」の行でも確かめたいこと
EXTRA = {
    "40130": ["教育支援センターの「すまいる学級」は小学校の建物の中にあります。在籍校に関係なく通える教室、という理解で合っていますか。"],
    "40342": ["「篠栗町教育支援センター」は、相談の窓口ですか。不登校の児童生徒が通える教室もありますか。"],
    "40349": ["教育相談室「ぽると」のサポートルームは、教育支援センター(適応指導教室)にあたるものですか。"],
    "40219": ["出席扱いにしているフリースクール等の一覧は、いまも市のページで公表されていますか。"],
    "40224": ["出席扱いのガイドラインにある「別紙の一覧表」は、公表されていますか。"],
}

LETTER = """## 文面(メール・問い合わせフォーム用)

件名: 不登校支援の制度についての問い合わせ(オープンデータ作成のため)

◯◯市(町)教育委員会 ご担当者様

福岡市在住の◯◯と申します。福岡県内の市町村ごとの不登校支援の制度を、公式の出典と確認日を付けて一覧にするオープンデータを、個人で作成しています(LODチャレンジ2026に応募する予定です)。

貴市(町)の公式サイトを拝見しましたが、下の点について記載を見つけられませんでした。「ある」「ない」だけでもかまいませんので、お教えいただけますでしょうか。

(ここに、下の一覧から貴市町の質問を貼る)

いただいた回答は、回答日と担当課名を付けて、次のデータに載せたいと考えています。担当の方のお名前は載せません。載せてよいかどうかも、あわせてお知らせください。

- データ: https://github.com/h-kazuki-pixel/futoko-shien-lod
- ライセンス: CC BY 4.0
- 載せる内容: 制度の有無、制度名、金額や対象などの項目、出典のURL、確認日、担当課名

お忙しいところ恐れ入りますが、よろしくお願いいたします。

◯◯(氏名)
連絡先: ◯◯

## 電話で聞くとき

1. 名乗る: 「福岡市に住んでいる◯◯です。県内の市町村の不登校支援の制度を一覧にするオープンデータを作っています」
2. 質問を1つずつ聞く。「ある」「ない」「分からない」を聞き分ける。「分からない」「担当が違う」は「なし」にしない
3. 「ある」なら、制度名と、載っているページや要綱の場所を聞く
4. 最後に、回答を担当課名つきで公開データに載せてよいかを聞く
5. 切ったらすぐ、日付・担当課・回答を `data/toiawase.csv` に書く

## 回答の記録と、データへの反映

- 記録は `data/toiawase.csv`。列: 日付、市町村コード、市町村、担当課、方法(電話/メール/フォーム)、種類、回答、公開の可否、反映した id
- 担当の方の個人名は書かない
- 「ない」と答えてもらえた種類は、状態を「なし」にし、「なしの根拠」に「日付・担当課・方法」を書く。確認方法は「問い合わせ」
- 「ある」と答えてもらえた種類は、教わったページを読んで「あり」の候補にし、照合に通す。ページが無い制度は、要綱の場所を聞く
- 回答が無い、分からないと言われた種類は「確認できず」のまま。備考に、問い合わせた日を書く
- 公開の可否が「不可」のときは、回答をデータに使わない
"""


def build() -> str:
    rows = schema.load("data/seido.csv")
    areas = [a for a in schema.read_csv("data/shichoson.csv") if a["福岡都市圏"] == "○"]
    cell = {(r["市町村コード"], schema.KIND_BY_LABEL[r["制度の種類"]]): r for r in rows}
    out = [
        "# 市町への問い合わせ",
        "",
        f"このファイルは `scripts/toiawase.py` がデータから作る({dt.date.today().isoformat()} 時点)。手で直さない。",
        "",
        "公式サイトを読んでも分からなかったことを、市町に聞く。目的は、「確認できず」を「あり」か「なし」に変えること。"
        "「なし」は、市町が無いと答えた記録があって初めて書ける。",
        "",
        LETTER,
        "## 市町ごとの質問",
        "",
    ]
    total = 0
    for a in areas:
        code, name = a["市町村コード"], a["市町村"]
        qs = []
        for k in KINDS:
            r = cell.get((code, k))
            if r is None or r["状態"] == "確認できず":
                qs.append(QUESTION[k])
        qs += EXTRA.get(code, [])
        if not qs:
            continue
        total += len(qs)
        unit = "町" if name.endswith("町") else "市"
        out.append(f"### {name}({len(qs)}問)")
        out.append("")
        for i, q in enumerate(qs, 1):
            out.append(f"{i}. {q.replace('市(町)', unit)}")
        out.append("")
    out.insert(6, f"いま聞くことは、福岡都市圏の17市町で合わせて{total}問。")
    out.insert(7, "")
    return "\n".join(out)


def main() -> int:
    Path("docs/問い合わせ.md").write_text(build(), encoding="utf-8")
    print(build().split("## 市町ごとの質問")[0].splitlines()[6])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
